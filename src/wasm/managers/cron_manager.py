"""
User cron jobs as first-class systemd timers.

Follows the shape of :mod:`wasm.managers.backup_scheduler`: a timer/service
unit pair named ``wasm-cron-{name}``, rendered through the escaped systemd
templates, written through :mod:`wasm.core.fs` and driven through the shared
:class:`~wasm.core.runner.CommandRunner`, so ``--dry-run`` reaches the unit
files and no test can touch a real systemctl.

Two decisions define this module:

- **The command is an argv, never a shell.** The operator types one command
  line; it is split with :func:`shlex.split` and written to ``ExecStart``
  token by token. systemd itself runs no shell, so pipes, ``&&`` and globs in
  that line are inert text handed to the program as arguments - which is the
  honest behaviour to expose. An operator who wants shell features writes
  ``/bin/sh -c '...'`` explicitly, and the quoted script travels as the single
  argument shlex parsed it as.
- **Only units carrying the WASM marker are touched.** Every unit this module
  writes carries ``Generated by WASM`` (the same marker
  :class:`~wasm.managers.service_manager.ServiceManager` recognises); every
  mutation first reads the unit file back and refuses when the marker is
  missing, so a hand-written ``wasm-cron-*`` unit is never overwritten,
  started or deleted by the panel.

The calendar expression is validated by
:func:`wasm.managers.backup_scheduler.validate_calendar` - the single
definition of what WASM writes after ``OnCalendar=`` - and only re-worded here
so the refusal talks about cron jobs instead of backups.
"""

