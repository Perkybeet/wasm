    def _write_unit_atomically(self, path: Path, content: str) -> None:
        """
        Write a unit file so that no reader ever sees a partial one.

        This used to open its own ``mkstemp``, fsync it and ``os.replace`` it
        into position. :meth:`~wasm.core.fs.FileSystem.write_text` already does
        exactly that - sibling temporary, fsync, atomic rename, mode applied at
        creation - so the copy is gone: two implementations of an atomic write
        means one of them eventually stops being atomic, and only one of them
        can be turned off by ``--dry-run``.

        Args:
            path: Final unit file path.
            content: Complete unit file body.

        Raises:
            ServiceError: When the file cannot be written or renamed.
        """
        try:
            self.fs.write_text(path, content, mode=UNIT_FILE_MODE)
        except OSError as exc:
            raise ServiceError(
                f"Failed to write unit file: {path}",
                details=(
                    f"{exc}. The previous unit file, if any, is untouched. "
                    f"Check that {path.parent} exists and is writable by root."
                ),
            ) from exc

    def _render_unit(self, template: str, context: Mapping[str, Any]) -> str:
        """
        Render a unit file from a packaged template.

        Args:
            template: Template name without the ``.service.j2`` suffix.
            context: Variables handed to the template.

        Returns:
            The rendered unit file.

        Raises:
            ServiceError: When the template environment is unavailable.
            TemplateError: If the unit template is missing or invalid.
        """
        if not self.jinja_env:
            raise ServiceError(
                "Template environment not initialized",
                details="Reinstall wasm so that the packaged systemd templates are available.",
            )

        try:
            template_obj = self.jinja_env.get_template(f"{template}.service.j2")
            return template_obj.render(**context)
        except TemplateNotFound as exc:
            raise TemplateError(f"Template not found: {template}.service.j2") from exc
        except JinjaTemplateError as exc:
            raise TemplateError(f"Template rendering failed: {exc}") from exc

    def create_service(
        self,
        name: str,
        command: str = "",
        working_directory: str = "",
        user: str | None = None,
        group: str | None = None,
        environment: dict[str, str] | None = None,
        description: str | None = None,
        template: str = "app",
        limits: ResourceLimits | None = None,
        environment_file: str | None = None,
        **kwargs: Any,
    ) -> None:
        """
        Create a new systemd service.

        This is the mandatory step for every caller that installs a unit, so it
        is where the name and the environment are validated: the deployers and
        the web API used to reach the templates without passing through either
        check.

        Args:
            name: Service name.
            command: Command to execute (not required for docker-compose template).
            working_directory: Working directory for the service.
            user: User to run service as.
            group: Group to run service as.
            environment: Environment variables written inline. Only what is
                not secret: every local user can read them.
            description: Service description.
            template: Template name.
            limits: Memory, CPU and task limits, validated here. None for none.
            environment_file: Absolute path of a 0600 file the unit loads the
                rest of its environment from, or None for none. A missing file
                is not an error: the unit references it with ``-``.
            **kwargs: Extra context variables passed to the template.

        Raises:
            ServiceError: If the unit already exists, would eclipse a unit
                shipped by the distribution, or cannot be written.
            TemplateError: If the unit template is missing or invalid.
            ValidationError: If the name, the environment or a directive value
                is unsafe.
        """
        unit = self._get_service_name(name)
        env = validate_environment(environment or {})

        info = self.inspect_unit(unit)
        if info.exists:
            if info.managed:
                raise ServiceError(
                    f"Service already exists: {info.unit}",
                    details=f"Delete it first, or edit {info.path}.",
                )
            raise ServiceError(
                f"Refusing to create a unit that is not WASM's to create: {info.unit}",
                details=f"{info.reason}. Choose a different service name.",
            )

        ctx: dict[str, Any] = {
            "name": unit,
            "description": validate_unit_value(
                description or f"WASM managed service: {unit}", field="Description"
            ),
            "command": validate_unit_value(command, field="ExecStart"),
            "working_directory": validate_unit_value(working_directory, field="WorkingDirectory"),
            "user": validate_unit_value(user or self.config.service_user, field="User"),
            "group": validate_unit_value(group or self.config.service_group, field="Group"),
            "environment": env,
            "environment_file": self._validated_environment_file(environment_file),
            "resource_limits": (limits or ResourceLimits()).validated().directives(),
        }
        ctx.update(kwargs)

        unit_file = self._get_service_file(unit)
        content = self._render_unit(template, ctx)
        self._write_unit_atomically(unit_file, content)
        self.daemon_reload()

        try:
            self.store.create_service(
                Service(
                    name=unit,
                    unit_file=str(unit_file),
                    command=command,
                    working_directory=working_directory,
                    user=str(ctx["user"]),
                    group=str(ctx["group"]),
                    environment=env,
                    status="inactive",
                    enabled=False,
                )
            )
        except (WASMError, sqlite3.Error) as exc:
            self.logger.debug(f"Could not register service in store: {exc}")

        self.logger.debug(f"Created service: {unit}")

    @staticmethod
    def _validated_environment_file(path: str | None) -> str | None:
        """
        Check an ``EnvironmentFile=`` path before it is written into a unit.

        Args:
            path: The path, or None.

        Returns:
            The path unchanged, or None.

        Raises:
            ValidationError: When the path is relative, or carries a character
                that would end the directive.
        """
        if path is None:
            return None
        value = validate_unit_value(path, field="EnvironmentFile")
        if not os.path.isabs(value):
            raise ValidationError(
                f"EnvironmentFile must be an absolute path, got {value!r}",
                details="systemd refuses a relative EnvironmentFile= and would not start the unit.",
            )
        return value

    def create_from_unit(self, name: str, content: str) -> None:
        """
        Create a unit from a complete file the caller wrote by hand.

        This exists because the panel offers an advanced mode where an operator
        supplies the whole unit. That mode used to write the file directly,
        which meant it could put any content at any unit path as root while the
        ownership guard on this class looked on. Routing it here applies the
        same rules as every other write.

        Args:
            name: Service name.
            content: Complete unit file body.

        Raises:
            ServiceError: When a unit of that name already exists anywhere
                systemd looks, when the body lacks the WASM marker, or when the
                write fails.
            ValidationError: When the name is not a safe unit name.
        """
        unit = self._get_service_name(name)
        self._check_unit_body(unit, content)

        info = self.inspect_unit(unit)
        if info.exists:
            if info.managed:
                raise ServiceError(
                    f"Service already exists: {info.unit}",
                    details=f"Delete it first, or edit {info.path}.",
                )
            raise ServiceError(
                f"Refusing to create a unit that is not WASM's to create: {info.unit}",
                details=f"{info.reason}. Choose a different service name.",
            )

        self._write_unit_atomically(self._get_service_file(unit), content)
        self.daemon_reload()

    def install_unit(self, name: str, template: str, context: Mapping[str, Any]) -> Path:
        """
        Write one of WASM's own units under exactly the name given.

        :meth:`create_service` names an application's unit and drops the legacy
        ``wasm-`` prefix, and refuses a unit that already exists. WASM's own
        units (the console's ``wasm-web``) keep the prefix, because it is what
        marks them as WASM's, and are rewritten in place when their options
        change. The ownership rule is the same one every other operation
        applies: systemd must load the unit from the managed directory, it must
        not eclipse a unit the system ships, and a file already there must be
        WASM's.

        Args:
            name: Unit name, with or without the ``.service`` suffix. Kept as
                given, prefix included.
            template: Template name without the ``.service.j2`` suffix.
            context: Variables handed to the template. Values interpolated into
                a directive are the caller's to validate.

        Returns:
            The unit file that was written.

        Raises:
            ServiceError: When the unit is not WASM's to write, the rendered
                body lacks the marker, or the file cannot be written.
            TemplateError: If the template is missing or invalid.
            ValidationError: When the name is not a safe unit name.
        """
        unit = validate_service_name(str(name).removesuffix(".service"))
        path = self.SYSTEMD_DIR / f"{unit}.service"
        content = self._render_unit(template, context)
        self._check_unit_body(unit, content)

        reason = self._refusal(
            unit,
            path,
            fragment=self._fragment_path(f"{unit}.service"),
            shadowed=self._shadowing_file(unit),
            # A new file carries the marker checked above; an existing one has
            # to show it is WASM's before it is replaced.
            signal=lambda: not path.exists() or self._carries_wasm_signal(unit, path),
        )
        if reason:
            raise ServiceError(
                f"Refusing to write a unit WASM does not manage: {unit}",
                details=f"{reason}. Remove or rename that unit first.",
            )

        self._write_unit_atomically(path, content)
        self.daemon_reload()
        return path

    def _check_unit_body(self, unit: str, content: str) -> None:
        """
        Reject a unit body that WASM must not write.

        Args:
            unit: Unit name, for the error message.
            content: Candidate unit body.

        Raises:
            ServiceError: When the marker is missing or the body is not text.
        """
        if WASM_UNIT_MARKER not in content:
            raise ServiceError(
                f"Refusing to write a unit without the WASM marker: {unit}",
                details=(
                    f"Keep the '# {WASM_UNIT_MARKER}' comment in the file. Without it "
                    "WASM stops recognising the unit as its own and refuses to manage it."
                ),
            )
        if "\x00" in content:
            raise ServiceError(
                f"Refusing to write a unit containing a NUL byte: {unit}",
                details="A unit file is text; a NUL byte would truncate it.",
            )

    def update_config(self, name: str, content: str) -> str:
        """
        Replace the body of a unit WASM manages.

        Args:
            name: Service name.
            content: Complete replacement unit file.

        Returns:
            The previous unit body, so the caller can revert by passing it back
            to this method.

        Raises:
            ServiceError: When the unit is not WASM's, cannot be read, or the
                new body would drop the marker that identifies it as ours.
            ValidationError: When the name is not a safe unit name.
        """
        info = self._require_managed(name, operation="rewrite")

        if WASM_UNIT_MARKER not in content:
            raise ServiceError(
                f"Refusing to write a unit without the WASM marker: {info.unit}",
                details=(
                    f"Keep the '# {WASM_UNIT_MARKER}' comment in the file. Without it "
                    "WASM stops recognising the unit as its own and refuses to manage it."
                ),
            )

        if "\x00" in content:
            raise ServiceError(
                f"Refusing to write a unit containing a NUL byte: {info.unit}",
                details="A unit file is text; a NUL byte would truncate it.",
            )

        try:
            previous = info.path.read_text()
        except OSError as exc:
            raise ServiceError(
                f"Could not read the current unit file: {info.path}",
                details=str(exc),
            ) from exc

        self._write_unit_atomically(info.path, content)
        self.daemon_reload()
        return previous

    def set_resource_limits(self, name: str, limits: ResourceLimits) -> str:
        """
        Give a unit WASM manages exactly these limits.

        The chokepoint for limits: they are validated here, whoever asks, and
        written through :meth:`update_config`, which keeps the ownership rules
        and reloads systemd. The running process keeps the limits it started
        with until it is restarted.

        Args:
            name: Service name.
            limits: The limits the unit must have.

        Returns:
            The previous unit body, to put back with :meth:`update_config`.

        Raises:
            ValidationError: A limit is out of range.
            ServiceError: The unit is not WASM's, or cannot be read or written.
        """
        limits.validated()
        info = self._require_managed(name, operation="limit")
        try:
            body = info.path.read_text()
        except OSError as exc:
            raise ServiceError(
                f"Could not read the current unit file: {info.path}", details=str(exc)
            ) from exc
        return self.update_config(name, with_resource_limits(body, limits))

    def delete_service(self, name: str) -> None:
        """
        Delete a service.

        Args:
            name: Service name.

        Raises:
            ServiceError: If the unit is not managed by WASM, or if the unit
                file cannot be removed.
            ValidationError: When the name is not a safe unit name.
        """
        info = self._require_managed(name, operation="delete", missing_ok=True)

        if info.exists:
            self._exec(["systemctl", "stop", info.unit_file], timeout=_LIFECYCLE_TIMEOUT)
            self._exec(["systemctl", "disable", info.unit_file])

            try:
                self.fs.remove(info.path, missing_ok=True)
            except OSError as exc:
                raise ServiceError(
                    f"Failed to delete service: {info.unit}",
                    details=str(exc),
                ) from exc

            self.daemon_reload()

        try:
            self.store.delete_service(info.unit)
        except (WASMError, sqlite3.Error) as exc:
            self.logger.debug(f"Could not remove service from store: {exc}")

        self.logger.debug(f"Deleted service: {info.unit}")

    # Lifecycle ------------------------------------------------------------

    def _reset_start_limit(self, info: UnitOwnership) -> None:
        """
        Clear a unit's failed state and start-limit counter before a deliberate start.

        App units carry ``StartLimitBurst=``, so a crash loop ends in
        ``failed`` instead of restarting forever. systemd applies that limit to
        every start, manual ones included: after a release crash-looped in the
        health gate, the rollback's restart of the previous release was refused
        with "start request repeated too quickly". An operator's or WASM's own
        start is a decision, not a loop, so it is always tried. The result is
        ignored: on a unit that is not failed this does nothing.

        Args:
            info: The unit, already checked to be WASM's.
        """
        self._exec(["systemctl", "reset-failed", info.unit_file])

    def start(self, name: str) -> None:
        """
        Start a service.

        Args:
            name: Service name.

        Raises:
            ServiceError: If the unit is not WASM's, does not exist, or systemd
                refuses to start it.
            ValidationError: When the name is not a safe unit name.
        """
        info = self._require_managed(name, operation="start")
        self._reset_start_limit(info)
        result = self._exec(["systemctl", "start", info.unit_file], timeout=_LIFECYCLE_TIMEOUT)

        if not result.success:
            raise ServiceError(
                f"Failed to start service: {info.unit}",
                details=result.stderr,
            )

        self._update_stored_status(info.unit, "active")

    def stop(self, name: str) -> bool:
        """
        Stop a service.

        Args:
            name: Service name.

        Returns:
            True when the unit is stopped afterwards, including when there was
            nothing to stop. Teardown paths call this before knowing whether
            the unit was ever created.

        Raises:
            ServiceError: If the unit exists but is not WASM's.
            ValidationError: When the name is not a safe unit name.
        """
        info = self._require_managed(name, operation="stop", missing_ok=True)
        if not info.exists:
            self.logger.debug(f"Nothing to stop: {info.unit} does not exist")
            return True

        result = self._exec(["systemctl", "stop", info.unit_file], timeout=_LIFECYCLE_TIMEOUT)
        self._update_stored_status(info.unit, "inactive")
        return result.success

    def restart(self, name: str) -> None:
        """
        Restart a service.

        Args:
            name: Service name.

        Raises:
            ServiceError: If the unit is not WASM's, does not exist, or systemd
                refuses to restart it.
            ValidationError: When the name is not a safe unit name.
        """
        info = self._require_managed(name, operation="restart")
        self._reset_start_limit(info)
        result = self._exec(["systemctl", "restart", info.unit_file], timeout=_LIFECYCLE_TIMEOUT)

        if not result.success:
            raise ServiceError(
                f"Failed to restart service: {info.unit}",
                details=result.stderr,
            )

        self._update_stored_status(info.unit, "active")

    def enable(self, name: str) -> bool:
        """
        Enable a service to start on boot.

        Args:
            name: Service name.

        Returns:
            True if systemd accepted the change.

        Raises:
            ServiceError: If the unit is not WASM's or does not exist.
            ValidationError: When the name is not a safe unit name.
        """
        info = self._require_managed(name, operation="enable")
        result = self._exec(["systemctl", "enable", info.unit_file])

        self._set_stored_enabled(info.unit, True)
        return result.success

    def disable(self, name: str) -> bool:
        """
        Disable a service from starting on boot.

        Args:
            name: Service name.

        Returns:
            True when the unit no longer starts on boot, including when it does
            not exist.

        Raises:
            ServiceError: If the unit exists but is not WASM's.
            ValidationError: When the name is not a safe unit name.
        """
        info = self._require_managed(name, operation="disable", missing_ok=True)
        if not info.exists:
            self.logger.debug(f"Nothing to disable: {info.unit} does not exist")
            return True

        result = self._exec(["systemctl", "disable", info.unit_file])

        self._set_stored_enabled(info.unit, False)
        return result.success

    def _update_stored_status(self, service_name: str, status: str) -> None:
        """
        Record a status change in the store, tolerating a missing record.

        Args:
            service_name: Resolved unit name.
            status: New status value.
        """
        try:
            self.store.update_service_status(service_name, status)
        except (WASMError, sqlite3.Error) as exc:
            self.logger.debug(f"Could not update service status in store: {exc}")

    def _set_stored_enabled(self, service_name: str, enabled: bool) -> None:
        """
        Record the enabled flag in the store, tolerating a missing record.

        Args:
            service_name: Resolved unit name.
            enabled: Whether the unit starts on boot.
        """
        try:
            svc = self.store.get_service(service_name)
            if svc:
                svc.enabled = enabled
                self.store.update_service(svc)
        except (WASMError, sqlite3.Error) as exc:
            self.logger.debug(f"Could not update service in store: {exc}")

    # Logs -----------------------------------------------------------------

    @staticmethod
    def _line_count(lines: int) -> str:
        """
        Normalise the number of journal lines to ask for.

        Args:
            lines: Requested line count.

        Returns:
            A positive integer as a string, ready for argv.

        Raises:
            ServiceError: When the value is not a number.
        """
        try:
            return str(max(1, int(lines)))
        except (TypeError, ValueError) as exc:
            raise ServiceError(
                f"Invalid number of log lines: {lines!r}",
                details="Pass a positive integer.",
            ) from exc

    def logs(self, name: str, lines: int = 50) -> str:
        """
        Get service logs.

        Args:
            name: Service name.
            lines: Number of lines to return.

        Returns:
            Log output, or journalctl's error output when it failed.

        Raises:
            ServiceError: If the unit is not WASM's or does not exist.
            ValidationError: When the name is not a safe unit name.
        """
        info = self._require_managed(name, operation="read the logs of")

        result = self._exec(
            ["journalctl", "-u", info.unit_file, "-n", self._line_count(lines), "--no-pager"]
        )
        return result.stdout if result.success else result.stderr

    def follow_logs(
        self,
        name: str,
        on_line: Callable[[str], None],
        lines: int = 50,
        timeout: int = _FOLLOW_TIMEOUT,
    ) -> None:
        """
        Follow service logs, delivering each line as it appears.

        ``wasm service logs --follow`` used to call :mod:`subprocess` directly,
        which is the one execution path the runner cannot enforce a deadline,
        a dry run or an audit record on.

        Args:
            name: Service name.
            on_line: Called once per line, without the trailing newline.
            lines: Number of past lines to replay before following.
            timeout: Deadline in seconds for the whole follow.

        Raises:
            ServiceError: If the unit is not WASM's or does not exist.
            ValidationError: When the name is not a safe unit name.
        """
        info = self._require_managed(name, operation="read the logs of")

        self.runner.stream(
            ["journalctl", "-u", info.unit_file, "-n", self._line_count(lines), "-f"],
            on_line=on_line,
            timeout=timeout,
        )

    def get_service_config(self, name: str) -> str | None:
        """
        Get service configuration content.

        Args:
            name: Service name.

        Returns:
            Unit file content, or None when WASM manages no such unit.

        Raises:
            ServiceError: If the unit exists but is not WASM's.
            ValidationError: When the name is not a safe unit name.
        """
        info = self._require_managed(name, operation="read", missing_ok=True)
        if not info.exists:
            return None

        try:
            return info.path.read_text()
        except OSError as exc:
            self.logger.debug(f"Could not read unit file {info.path}: {exc}")
            return None

    def verify_unit(self, content: str) -> tuple[bool, str]:
        """
        Check a candidate unit file with systemd-analyze, without installing it.

        Used by the unit editor to catch a mistake before it ever reaches a
        unit WASM or systemd has to reload. The candidate never touches the
        managed directory: it is staged into a private scratch directory,
        the same containment ``WebServerBackend.validate_config`` uses for
        an nginx or apache snippet, and removed once the check is done,
        success or failure alike.

        Args:
            content: Candidate unit file content, verbatim.

        Returns:
            Whether it verified cleanly, and the checker's own output,
            verbatim - empty on a clean pass, since systemd-analyze says
            nothing when there is nothing to say.

        Raises:
            ServiceError: When the scratch directory or file cannot be
                staged.
        """
        staging = Path(tempfile.gettempdir()) / f"wasm-verify-{os.urandom(6).hex()}"
        candidate = staging / "wasm-verify.service"
        try:
            try:
                self.fs.make_dir(staging, mode=SECRET_DIR_MODE, parents=True, exist_ok=False)
                self.fs.write_text(candidate, content, mode=SECRET_MODE)
            except OSError as exc:
                raise ServiceError(
                    "Could not stage the unit file for verification", details=str(exc)
                ) from exc

            result = self._exec(
                ["systemd-analyze", "verify", str(candidate)], timeout=VERIFY_TIMEOUT
            )
        finally:
            if staging.exists():
                self.fs.remove_tree(staging)

        output = "\n".join(stream for stream in (result.stderr, result.stdout) if stream.strip())
        return result.success, output
