class ServiceManager(BaseManager):
    """
    Manager for systemd services.

    Handles creating, starting, stopping, and managing systemd services. Every
    public method refuses to act on a unit WASM does not own; see the module
    docstring for what ownership means.
    """

    SYSTEMD_DIR = SYSTEMD_DIR

    #: Every directory systemd loads units from, most specific first. Ownership
    #: is decided against all of them: looking only at ``/etc/systemd/system``
    #: is what let ``delete ssh`` through, because sshd lives in ``/usr/lib``.
    UNIT_SEARCH_DIRS: tuple[Path, ...] = (
        SYSTEMD_DIR,
        Path("/run/systemd/system"),
        Path("/run/systemd/transient"),
        Path("/etc/systemd/system.control"),
        Path("/usr/local/lib/systemd/system"),
        Path("/usr/lib/systemd/system"),
        Path("/lib/systemd/system"),
    )

    #: Prefix carried by every unit this project created before the name was
    #: shortened. New units drop it and are recognised through the store or the
    #: unit-file marker instead.
    SERVICE_PREFIX = "wasm-"
    LEGACY_PREFIX = SERVICE_PREFIX

    def __init__(
        self,
        verbose: bool = False,
        runner: CommandRunner | None = None,
        fs: FileSystem | None = None,
    ):
        """
        Initialize service manager.

        Args:
            verbose: Enable verbose logging.
            runner: Command runner to execute systemd with. Defaults to the
                process-wide runner.
            fs: Filesystem to write unit files through. Defaults to the
                process-wide one, which is what makes ``--dry-run`` refuse to
                install or delete a unit.
        """
        super().__init__(verbose=verbose, runner=runner, fs=fs)
        self.store = get_store()

        try:
            # Unit files are not markup: autoescaping would corrupt ExecStart.
            self.jinja_env: Environment | None = Environment(
                loader=PackageLoader("wasm", "templates/systemd"),
                trim_blocks=True,
                lstrip_blocks=True,
                autoescape=False,  # noqa: S701
            )
        except (ImportError, ValueError, OSError) as exc:
            # A missing template package is not fatal: everything except
            # create_service keeps working.
            self.logger.debug(f"Systemd template environment unavailable: {exc}")
            self.jinja_env = None

    def _exec(self, argv: list[str], *, timeout: int = DEFAULT_TIMEOUT) -> CommandResult:
        """
        Run a command through the shared runner.

        WASM requires root, so nothing here is prefixed with sudo: a manager
        that shells out to sudo hides which identity the change was made under
        and breaks on hosts where sudo is not installed.

        Args:
            argv: Program and arguments.
            timeout: Deadline in seconds.

        Returns:
            The command outcome.
        """
        return self.runner.run(argv, timeout=timeout)

    def is_installed(self) -> bool:
        """
        Check if systemd is available.

        Returns:
            True when systemctl can be executed.
        """
        return self.runner.exists("systemctl")

    def get_version(self) -> str | None:
        """
        Get systemd version.

        Returns:
            The major version as a string, or None when it cannot be read.
        """
        result = self._exec(["systemctl", "--version"])
        if result.success:
            match = re.search(r"systemd (\d+)", result.stdout)
            if match:
                return match.group(1)
        return None

    # Naming ---------------------------------------------------------------

    def _get_service_name(self, name: str) -> str:
        """
        Get the validated service name for new services (no prefix).

        Args:
            name: Base service name, with or without the ``.service`` suffix.

        Returns:
            Service name without prefix or suffix.

        Raises:
            ValidationError: When the name is not a safe unit name.
        """
        candidate = validate_service_name(str(name).removesuffix(".service"))
        return candidate.removeprefix(self.LEGACY_PREFIX) or candidate

    #: Units WASM runs for itself, not for an application.
    OWN_UNITS: ClassVar[frozenset[str]] = frozenset({"wasm-web", "wasm-monitor"})
    #: Prefixes of the units WASM writes for scheduled work.
    OWN_UNIT_PREFIXES: ClassVar[tuple[str, ...]] = ("wasm-cron-", "wasm-backup-")

    @classmethod
    def _is_own_unit_name(cls, name: str) -> bool:
        """
        Report whether a unit name is one of WASM's own, never an application's.

        Args:
            name: Unit name without the ``.service`` suffix.

        Returns:
            True for the console, the monitor and the scheduled-work units.
        """
        return name in cls.OWN_UNITS or name.startswith(cls.OWN_UNIT_PREFIXES)

    def _resolve_service_name(self, name: str) -> str:
        """
        Resolve actual service name, checking both new and legacy formats.

        For backwards compatibility, checks if a legacy (``wasm-*``) unit exists
        and returns that if found. Otherwise returns the new format.

        Args:
            name: Base service name.

        Returns:
            Actual service name (may have legacy prefix if it exists).

        Raises:
            ValidationError: When the name is not a safe unit name.
        """
        given = validate_service_name(str(name).removesuffix(".service"))

        if given.startswith(self.LEGACY_PREFIX):
            # A caller that spells the prefix means that unit. Only fall back to
            # the unprefixed form when it is the one actually installed,
            # otherwise the prefix - a WASM ownership signal - is thrown away.
            # WASM's own units are never an application's: "wasm-web" falling
            # back to an app named "web" would stop that app instead of the console.
            if self._is_own_unit_name(given):
                return given
            stripped = given.removeprefix(self.LEGACY_PREFIX) or given
            if (self.SYSTEMD_DIR / f"{given}.service").exists():
                return given
            if (self.SYSTEMD_DIR / f"{stripped}.service").exists():
                return stripped
            return given

        legacy_name = f"{self.LEGACY_PREFIX}{given}"
        if (self.SYSTEMD_DIR / f"{legacy_name}.service").exists():
            return legacy_name

        return given

    def _get_service_file(self, name: str) -> Path:
        """
        Get the unit file path a new service would be written to.

        Args:
            name: Service name.

        Returns:
            Path to the unit file inside the managed directory.

        Raises:
            ValidationError: When the name is not a safe unit name.
        """
        return self.SYSTEMD_DIR / f"{self._get_service_name(name)}.service"

    def _resolve_service_file(self, name: str) -> Path:
        """
        Resolve unit file path, checking both new and legacy formats.

        Args:
            name: Service name.

        Returns:
            Path to the existing unit file, or the new-format path when none
            exists.

        Raises:
            ValidationError: When the name is not a safe unit name.
        """
        return self.SYSTEMD_DIR / f"{self._resolve_service_name(name)}.service"

    # Ownership ------------------------------------------------------------

    def _stored_services(self) -> list[Service]:
        """
        The rows of the store's services table.

        Returns:
            Every recorded service. Empty when the store cannot be read, which
            only makes the ownership filter stricter.
        """
        try:
            return list(self.store.list_services())
        except (WASMError, sqlite3.Error) as exc:
            self.logger.debug(f"Could not read services from store: {exc}")
            return []

    def _stored_service_names(self) -> set[str]:
        """
        Names of the units the store knows this project created.

        Returns:
            Unit names without the ``.service`` suffix. Empty when the store
            cannot be read, which only makes the filter stricter.
        """
        return {service.name.removesuffix(".service") for service in self._stored_services()}

    def _stored_apps(self) -> list[App]:
        """
        The applications the store records.

        Returns:
            Every application. Empty when the store cannot be read.
        """
        try:
            return list(self.store.list_apps())
        except (WASMError, sqlite3.Error) as exc:
            self.logger.debug(f"Could not read applications from store: {exc}")
            return []

    def _marked_unit_files(self) -> dict[str, bool]:
        """
        Scan the managed directory for unit files that could be WASM's.

        Only regular files are read: a symlink in ``/etc/systemd/system`` is an
        alias or a mask pointing at somebody else's file. A name WASM could not
        have written (an escape, a template ending in ``@``) is skipped, since
        WASM validates every name it creates.

        Returns:
            Unit name (without ``.service``) to whether its file carries
            :data:`WASM_UNIT_MARKER`, for every ``.service`` file with a
            name WASM could have given it.
        """
        found: dict[str, bool] = {}
        try:
            entries = sorted(Path(self.SYSTEMD_DIR).iterdir())
        except OSError as exc:
            self.logger.debug(f"Could not scan {self.SYSTEMD_DIR}: {exc}")
            return found

        for entry in entries:
            if entry.suffix != ".service" or entry.is_symlink() or not entry.is_file():
                continue
            unit = entry.name.removesuffix(".service")
            try:
                validate_service_name(unit)
            except ValidationError:
                continue
            if unit.endswith("@"):
                continue
            found[unit] = self._file_has_marker(entry)
        return found

    @staticmethod
    def _file_has_marker(path: Path) -> bool:
        """
        Report whether a unit file carries the WASM marker.

        Args:
            path: The unit file.

        Returns:
            True when the file can be read and carries the marker.
        """
        try:
            return WASM_UNIT_MARKER in path.read_text(errors="replace")
        except OSError:
            return False

    def app_units(
        self,
        app: App,
        *,
        services: list[Service] | None = None,
        marked: Mapping[str, bool] | None = None,
        listed: Collection[str] = (),
    ) -> list[str]:
        """
        Name the unit(s) an application runs as.

        The one mapping from an application to its units; the log stream, the
        machine tally, ``wasm list`` and the migration all ask here. In order:

        1. The rows of the services table that carry the application's id: a
           monorepo has one per workspace.
        2. For a monorepo without rows, the marked unit files named
           ``<app-name>-<workspace>`` in the managed directory.
        3. The unit named after the application, or the legacy ``wasm-``
           prefixed one when that is the one installed (units from before
           0.14.1): its file is in the managed directory, or systemd lists it
           and knows nothing of the unprefixed name. Docker Compose
           applications are named the same way.

        Args:
            app: The application.
            services: The services table, when the caller has already read it.
            marked: What :meth:`_marked_unit_files` returned, when the caller
                has already scanned the directory.
            listed: Unit names systemd listed, when the caller has asked.

        Returns:
            Unit names without the ``.service`` suffix, primary first. Empty
            for a static application, which has no process.
        """
        # A site of the static type has no process, even when a unit was left
        # behind from a type it had before.
        if app.is_static or app.app_type == "static":
            return []

        rows = services if services is not None else self._stored_services()
        if app.id is not None:
            owned = sorted(
                {row.name.removesuffix(".service") for row in rows if row.app_id == app.id}
            )
            if owned:
                return owned

        base = domain_to_app_name(app.domain)
        if app.app_type == "monorepo":
            files = marked if marked is not None else self._marked_unit_files()
            workspaces = sorted(
                name
                for name, has_marker in files.items()
                if has_marker and name.startswith(f"{base}-")
            )
            if workspaces:
                return workspaces

        legacy = f"{self.LEGACY_PREFIX}{base}"
        directory = Path(self.SYSTEMD_DIR)
        if (directory / f"{legacy}.service").exists():
            return [legacy]
        if legacy in listed and base not in listed and not (directory / f"{base}.service").exists():
            return [legacy]
        return [base]

    def _app_unit_owners(
        self,
        apps: list[App],
        services: list[Service],
        marked: Mapping[str, bool] | None = None,
        listed: Collection[str] = (),
    ) -> dict[str, str]:
        """
        Map every application unit to the domain it serves.

        Args:
            apps: The applications.
            services: The services table.
            marked: The directory scan, when already done.
            listed: Unit names systemd listed, when already asked.

        Returns:
            Unit name to application domain.
        """
        owners: dict[str, str] = {}
        for app in apps:
            for unit in self.app_units(app, services=services, marked=marked, listed=listed):
                owners.setdefault(unit, app.domain)
        return owners

    def _is_managed_dir(self, directory: Path) -> bool:
        """
        Report whether a directory is the one WASM writes units into.

        Args:
            directory: Candidate unit directory.

        Returns:
            True when it is the managed directory, comparing resolved paths so
            a symlinked ``/lib`` does not read as a second location.
        """
        if directory == self.SYSTEMD_DIR:
            return True
        try:
            return directory.resolve() == Path(self.SYSTEMD_DIR).resolve()
        except OSError:
            return False

    def _foreign_unit_dirs(self) -> list[Path]:
        """
        The unit directories that belong to the system, not to WASM.

        Returns:
            Every configured search directory except the managed one.
        """
        return [d for d in self.UNIT_SEARCH_DIRS if not self._is_managed_dir(d)]

    def _fragment_path(self, unit_file: str) -> Path | None:
        """
        Ask systemd where it loads a unit from.

        Args:
            unit_file: Full unit name, including the ``.service`` suffix.

        Returns:
            The path systemd reports, or None when systemd does not know the
            unit or cannot be reached.
        """
        result = self._exec(["systemctl", "show", "-p", "FragmentPath", unit_file])
        if not result.success:
            return None

        for line in result.stdout.splitlines():
            key, separator, value = line.partition("=")
            if separator and key.strip() == "FragmentPath":
                fragment = value.strip()
                return Path(fragment) if fragment else None
        return None

    def _carries_wasm_signal(
        self,
        unit: str,
        path: Path,
        *,
        stored: set[str] | None = None,
        app_owned: Mapping[str, str] | None = None,
        has_marker: bool | None = None,
    ) -> bool:
        """
        Report whether a unit shows any sign of having been created by WASM.

        The cheap signals are checked first, so a single lookup reads the store
        only when the name and the file said nothing.

        Args:
            unit: Unit name without the ``.service`` suffix.
            path: The unit file inside the managed directory.
            stored: The services table's names, when already read.
            app_owned: :meth:`_app_unit_owners`, when already computed.
            has_marker: Whether the file carries the marker, when already read.

        Returns:
            True when the prefix, the store, the file marker or an application
            in the store identifies it.
        """
        if unit.startswith(self.SERVICE_PREFIX):
            return True
        if unit in (stored if stored is not None else self._stored_service_names()):
            return True
        if has_marker if has_marker is not None else self._file_has_marker(path):
            return True
        if app_owned is None:
            app_owned = self._app_unit_owners(self._stored_apps(), self._stored_services())
        return unit in app_owned

    def _shadowing_file(self, unit: str) -> Path | None:
        """
        Find a same-named unit file in a directory the system owns.

        Args:
            unit: Unit name without the ``.service`` suffix.

        Returns:
            The first such file, or None.
        """
        return next(
            (
                d / f"{unit}.service"
                for d in self._foreign_unit_dirs()
                if (d / f"{unit}.service").exists()
            ),
            None,
        )

    def _refusal(
        self,
        unit: str,
        path: Path,
        *,
        fragment: Path | None,
        shadowed: Path | None,
        signal: Callable[[], bool],
    ) -> str:
        """
        Apply the ownership rule, and say why a unit is not WASM's.

        The rule itself, shared by :meth:`inspect_unit` (one unit, with
        systemd's FragmentPath) and :meth:`managed_units` (every unit, from the
        directory scan), so the listing and the guard cannot disagree.

        Args:
            unit: Unit name without the ``.service`` suffix.
            path: Its file inside the managed directory.
            fragment: Where systemd loads it from, when that was asked.
            shadowed: A same-named file in a system directory, if any.
            signal: Evaluates the WASM signals; only called when needed.

        Returns:
            Why the unit is not managed, or an empty string when it is.
        """
        if fragment is not None and not self._is_managed_dir(fragment.parent):
            return f"systemd loads it from {fragment}, outside {self.SYSTEMD_DIR}"

        if shadowed is not None:
            return (
                f"a unit with the same name is shipped by the system at {shadowed}; "
                "a file in the managed directory would eclipse it"
            )

        # Ownership is deliberately independent of existence: a unit systemd has
        # loaded but whose file this process cannot see is still ours when
        # nothing points at another owner. Callers ask about existence through
        # ``exists``, which is what decides whether an operation has a target.
        if not signal():
            return (
                f"{path} was not generated by WASM"
                if path.exists()
                else f"nothing identifies {unit} as a unit WASM created"
            )
        return ""

    def inspect_unit(self, name: str) -> UnitOwnership:
        """
        Decide whether a unit belongs to WASM, and why.

        Args:
            name: Unit name, with or without the ``.service`` suffix.

        Returns:
            The ownership verdict, including the reason when it is negative.

        Raises:
            ValidationError: When the name is not a safe unit name.
        """
        unit = self._resolve_service_name(name)
        path = self.SYSTEMD_DIR / f"{unit}.service"
        fragment = self._fragment_path(f"{unit}.service")
        shadowed = self._shadowing_file(unit)
        exists = path.exists() or shadowed is not None or fragment is not None

        reason = self._refusal(
            unit,
            path,
            fragment=fragment,
            shadowed=shadowed,
            signal=lambda: self._carries_wasm_signal(unit, path),
        )
        return UnitOwnership(
            unit=unit,
            path=path,
            fragment_path=fragment,
            exists=exists,
            managed=not reason,
            reason=reason,
        )

    def is_managed(self, name: str) -> bool:
        """
        Report whether a unit belongs to WASM.

        Args:
            name: Unit name, with or without the ``.service`` suffix.

        Returns:
            True when the unit was created by this project and still lives
            where this project puts its units. An unusable name is not managed
            rather than an error, so listings can call this on anything.
        """
        try:
            return self.inspect_unit(name).managed
        except WASMError as exc:
            self.logger.debug(f"Not a WASM unit name: {name!r}: {exc}")
            return False

    def _require_managed(
        self, name: str, *, operation: str, missing_ok: bool = False
    ) -> UnitOwnership:
        """
        Resolve a unit and refuse to operate on it unless WASM owns it.

        Args:
            name: Unit name, with or without the ``.service`` suffix.
            operation: Verb used in the error message.
            missing_ok: Return the verdict instead of raising when the unit does
                not exist anywhere. Used by the idempotent operations (stop,
                disable, delete, status), so teardown does not depend on knowing
                whether a unit was ever created.

        Returns:
            The ownership verdict. It is only returned with ``exists`` False
            when ``missing_ok`` is set.

        Raises:
            ServiceError: When the unit is not WASM's, or does not exist and
                ``missing_ok`` is False.
            ValidationError: When the name is not a safe unit name.
        """
        info = self.inspect_unit(name)

        # Existence is checked first: a name nobody has installed cannot belong
        # to anyone, and the caller decides whether that is an error.
        if not info.exists:
            if missing_ok:
                return info
            raise ServiceError(
                f"Unknown service: {info.unit}",
                details=(
                    f"There is no unit file at {info.path}. "
                    "Run 'wasm service list' to see the units WASM manages."
                ),
            )

        if info.managed:
            return info

        raise ServiceError(
            f"Refusing to {operation} a unit WASM does not manage: {info.unit}",
            details=(
                f"{info.reason}. Use systemctl directly if that is really what you want to do."
            ),
        )

