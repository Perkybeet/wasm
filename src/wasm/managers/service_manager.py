"""
Systemd service manager for WASM.

This module is the only door to systemd, and WASM runs as root, so the question
it has to answer before every single operation is *who owns this unit*. Getting
that wrong is not a cosmetic bug: ``wasm service delete ssh`` used to stop and
disable sshd, because the ownership guard only ran when a file existed under
``/etc/systemd/system`` and distribution units live in ``/usr/lib/systemd/system``.

Definition of a WASM-managed unit
---------------------------------
A unit belongs to WASM when **all three** hold:

1. **systemd loads it from the directory WASM manages.** The authority is
   ``systemctl show -p FragmentPath``, not a guess based on paths: it is one
   call and it reports where the unit actually comes from, including when a
   name in ``/etc`` is an alias for a file shipped by the distribution.
2. **It does not shadow a unit shipped with the system.** A file in our
   directory that eclipses ``/usr/lib/systemd/system/nginx.service`` is a
   takeover of the distribution's unit, not one of ours, and is refused even
   though it sits in the right directory.
3. **It carries a WASM signal**: the ``wasm-`` prefix (the historical naming
   scheme), a record in the store's services table, the ``Generated by WASM``
   marker written by the templates, or being the unit an application in the
   store runs as (:meth:`ServiceManager.app_units`). Several signals because
   any one of them can be missing on a server that has been upgraded or
   repaired by hand: since 0.14.1 app units carry no prefix, and a store that
   was moved or rebuilt has an empty services table.

Every operation that reads or changes unit state goes through
:meth:`ServiceManager.inspect_unit`, so the guard cannot be forgotten in one
code path the way it was before.

The units WASM manages, as a set
--------------------------------
:meth:`ServiceManager.managed_units` is the one answer to "which units are
WASM's": every unit file in the managed directory carrying a signal, plus the
unit(s) of every application in the store, judged by the same rule as
:meth:`~ServiceManager.inspect_unit`. The console's top bar, the Services page,
``wasm service list``, the live log stream and the monitor all read it. It
costs one ``systemctl list-units`` and a scan of one directory, because the
top bar asks for it every five seconds.

Secrets go in ``EnvironmentFile=``, not ``Environment=``
------------------------------------------------------
A unit file is 0644, and ``systemctl show <unit>`` prints its ``Environment=``
to any local user, not only to root: an unprivileged account on the machine
could read every DATABASE_URL and API key an application was deployed with.
So an application's unit carries inline only what is not secret and is WASM's
to decide (PORT, NODE_ENV), and loads the rest with ``EnvironmentFile=-`` from
the application's env file - the one
:func:`~wasm.deployers.helpers.layout.env_file_for` names, 0600 and owned by
the service account, which backups, restores and deletes already know about
because ``wasm env`` and the panel edit the same file.

Two consequences the callers own. systemd lets ``EnvironmentFile=`` override
``Environment=``, so the deployers keep PORT and NODE_ENV out of the file.
And the file is parsed by systemd as well as by the application, so it is
written in the one grammar both read the same way (see
:class:`~wasm.deployers.helpers.env_manager.EnvManager`). A unit written by
an earlier version, with the variables inline, keeps working as it is; the
next deploy moves them into the file.

Everything still interpolated into a unit is validated in
:meth:`ServiceManager.create_service` - mandatory, since this manager is the
single step every caller must pass through - and escaped at render time.
"""

