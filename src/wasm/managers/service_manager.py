    def service_exists(self, name: str) -> bool:
        """
        Check if a unit file exists in the managed directory.

        Args:
            name: Service name.

        Returns:
            True if the unit file exists, in either the new or legacy format.

        Raises:
            ValidationError: When the name is not a safe unit name.
        """
        return self._resolve_service_file(name).exists()

    @staticmethod
    def state_is_running(raw_state: str) -> bool:
        """
        Decide whether a systemd active-state string means "running".

        ``systemctl is-active`` and the ACTIVE column ``systemctl
        list-units`` prints share one vocabulary (``active``, ``inactive``,
        ``failed``, ``activating``, ``deactivating``, ``reloading``), and
        exactly one value of it means the unit is up. This is the one place
        that decides that, so :meth:`get_status` (which the web API reads)
        and a caller of :meth:`list_services` (``wasm service list``) cannot
        end up answering "is it running" two different ways.

        Args:
            raw_state: The raw string systemd reported.

        Returns:
            True when the state means the unit is running.
        """
        return raw_state.strip() == "active"

    @staticmethod
    def _parse_list_units(stdout: str) -> dict[str, dict[str, str]]:
        """
        Read the rows of ``systemctl list-units --plain``.

        Names are taken exactly as systemd writes them, escapes included: this
        is systemd's own output, not user input, and nothing here builds a
        path from it.

        Args:
            stdout: What systemctl printed.

        Returns:
            Unit name (without ``.service``) to its ``load``, ``active`` and
            ``sub`` columns, in the order systemd printed them.
        """
        rows: dict[str, dict[str, str]] = {}
        for line in stdout.splitlines():
            parts = line.split()
            if len(parts) < 4 or not parts[0].endswith(".service"):
                continue
            name = parts[0].removesuffix(".service")
            rows[name] = {"name": name, "load": parts[1], "active": parts[2], "sub": parts[3]}
        return rows

    def _list_units(self, patterns: list[str]) -> dict[str, dict[str, str]] | None:
        """
        Run one ``systemctl list-units`` and parse it.

        Args:
            patterns: Unit names or globs to ask about.

        Returns:
            The parsed rows, or None when systemctl failed.
        """
        result = self._exec([*LIST_UNITS_ARGV, *patterns])
        if not result.success:
            self.logger.debug(f"systemctl list-units failed: {result.stderr.strip()}")
            return None
        return self._parse_list_units(result.stdout)

    def managed_units(
        self, *, listing: Mapping[str, Mapping[str, str]] | None = None
    ) -> list[ManagedUnit]:
        """
        List the units WASM manages: the one definition every view reads.

        Candidates are the ``.service`` files in the managed directory that
        carry a WASM signal, the services table, the unit(s) of every
        application in the store (:meth:`app_units`) and the ``wasm-*`` units
        systemd has loaded. Each is judged by the rule :meth:`inspect_unit`
        applies, from the directory scan instead of a ``systemctl show`` per
        unit: the console's top bar calls this every five seconds.

        Args:
            listing: Rows of a ``systemctl list-units`` already run, such as the
                whole-machine one :meth:`list_services` makes; None runs one
                scoped to the candidates.

        Returns:
            One entry per unit, sorted by name. A unit whose file exists but
            that systemd has not loaded (stopped and disabled) is included as
            ``not-loaded``/``inactive``/``dead``; an application unit that
            exists nowhere is not.

        Raises:
            ServiceError: When systemctl cannot list units at all, so that a
                caller can tell "none" from "could not ask".
        """
        services = self._stored_services()
        stored = {service.name.removesuffix(".service") for service in services}
        marked = self._marked_unit_files()
        apps = self._stored_apps()

        candidates = {name for name, has_marker in marked.items() if has_marker} | {
            name for name in marked if name.startswith(self.SERVICE_PREFIX)
        }
        candidates |= stored | set(self._app_unit_owners(apps, services, marked))

        rows: Mapping[str, Mapping[str, str]] | None = listing
        if rows is None:
            # Full unit names, not bare ones: list-units matches its arguments
            # as globs against "name.service", so "shop-example-com" alone
            # matches nothing. Names that are not safe globs never get here:
            # every candidate passed validate_service_name or came from the
            # store, which only records validated names.
            patterns = [f"{self.SERVICE_PREFIX}*"]
            patterns += [f"{name}.service" for name in sorted(candidates) if _is_plain(name)]
            rows = self._list_units(patterns)
            if rows is None:
                raise ServiceError(
                    "Could not list systemd units",
                    details="Check that systemd is running: 'systemctl list-units' failed.",
                )

        # Asked again with what systemd listed: a legacy unit whose file this
        # process cannot see is still recognised as its application's.
        owners = self._app_unit_owners(apps, services, marked, listed=set(rows))
        candidates |= set(owners)
        candidates |= {name for name in rows if name.startswith(self.SERVICE_PREFIX)}

        units: list[ManagedUnit] = []
        for name in sorted(candidates):
            path = Path(self.SYSTEMD_DIR) / f"{name}.service"
            row = rows.get(name)
            on_disk = name in marked
            loaded = row is not None and row.get("load") != "not-found"
            if not on_disk and not loaded:
                continue
            reason = self._refusal(
                name,
                path,
                fragment=None,
                shadowed=self._shadowing_file(name),
                signal=partial(
                    self._carries_wasm_signal,
                    name,
                    path,
                    stored=stored,
                    app_owned=owners,
                    has_marker=marked.get(name, False),
                ),
            )
            if reason:
                continue
            units.append(
                ManagedUnit(
                    name=name,
                    load=row["load"] if row is not None else "not-loaded",
                    active=row["active"] if row is not None else "inactive",
                    sub=row["sub"] if row is not None else "dead",
                    app=owners.get(name),
                )
            )
        return units

    def list_services(self, all_services: bool = False) -> list[dict[str, Any]]:
        """
        List WASM-managed services, or every service on the machine.

        The managed listing is :meth:`managed_units`. Asking systemd for ``*``
        and filtering afterwards used to return ssh, cron and dbus, which then
        showed up as deletable in ``wasm service list``.

        Args:
            all_services: List every unit on the system as well, each flagged
                ``managed``. Opt-in, for diagnostics only. Foreign units are
                described from the one listing, never validated or probed one
                by one: a name systemd escaped (``\\x2d``) is still a unit.

        Returns:
            One dictionary per unit with ``name``, ``load``, ``active``,
            ``sub``, ``managed`` and ``app`` (the domain it serves, or None).
            Empty when systemd cannot be reached.
        """
        if not all_services:
            try:
                return [unit.as_dict() for unit in self.managed_units()]
            except ServiceError as exc:
                self.logger.debug(str(exc))
                return []

        listing = self._list_units(["*"])
        if listing is None:
            return []
        managed = {unit.name: unit for unit in self.managed_units(listing=listing)}
        rows: list[dict[str, Any]] = [unit.as_dict() for unit in managed.values()]
        rows += [
            {**row, "managed": False, "app": None}
            for name, row in listing.items()
            if name not in managed
        ]
        return sorted(rows, key=lambda row: str(row["name"]))

    def describe_units(self, names: list[str]) -> dict[str, dict[str, str]]:
        """
        Read systemd's properties for several units in one call.

        The Services page shows the PID, memory, uptime and boot setting of
        every unit WASM manages. Asking with three ``systemctl`` calls per unit,
        the way :meth:`get_status` does for one, is dozens of processes per page
        load; ``systemctl show`` answers for all of them at once.

        Args:
            names: Unit names without the ``.service`` suffix, as systemd or
                :meth:`managed_units` wrote them.

        Returns:
            Unit name to its :data:`DESCRIBE_PROPERTIES`. A unit systemd did
            not answer for is missing.
        """
        if not names:
            return {}
        result = self._exec(
            [
                "systemctl",
                "show",
                "--no-pager",
                "-p",
                ",".join(DESCRIBE_PROPERTIES),
                "--",
                *(f"{name}.service" for name in names),
            ]
        )
        if not result.success:
            self.logger.debug(f"systemctl show failed: {result.stderr.strip()}")
            return {}

        described: dict[str, dict[str, str]] = {}
        for block in result.stdout.split("\n\n"):
            properties: dict[str, str] = {}
            for line in block.splitlines():
                key, separator, value = line.partition("=")
                if separator:
                    properties[key.strip()] = value
            unit_id = properties.get("Id", "")
            if unit_id:
                described[unit_id.removesuffix(".service")] = properties
        return described

    @staticmethod
    def status_from_properties(
        name: str, properties: Mapping[str, str], *, managed: bool, exists: bool = True
    ) -> dict[str, Any]:
        """
        Shape systemd's properties the way :meth:`get_status` answers.

        Args:
            name: Unit name without the ``.service`` suffix.
            properties: From :meth:`describe_units`, or the ``active``/``sub``
                columns of a listing under ``ActiveState``/``SubState``.
            managed: Whether WASM manages the unit.
            exists: Whether a unit file for it exists.

        Returns:
            The same keys :meth:`get_status` returns.
        """
        return {
            "name": name,
            "exists": exists,
            "active": ServiceManager.state_is_running(properties.get("ActiveState", "")),
            "enabled": properties.get("UnitFileState", "").strip() == "enabled",
            "pid": properties.get("MainPID", ""),
            "memory": properties.get("MemoryCurrent", ""),
            "uptime": properties.get("ActiveEnterTimestamp", ""),
            "active_state": properties.get("ActiveState", ""),
            "sub_state": properties.get("SubState", ""),
            "restarts": properties.get("NRestarts", "0"),
            "result": properties.get("Result", ""),
            "managed": managed,
        }

    def list_statuses(self, all_services: bool = False) -> list[dict[str, Any]]:
        """
        Describe the units the Services page lists, each like :meth:`get_status`.

        Managed units are described with one ``systemctl show`` for all of
        them. With ``all_services``, a foreign unit is described from the
        listing alone (its state columns; no PID, memory or boot setting): it is
        shown, never acted on, and one odd unit can no longer fail the list.

        Args:
            all_services: Include every unit on the machine.

        Returns:
            One status mapping per unit, plus ``app``, sorted by name.
        """
        rows = self.list_services(all_services=all_services)
        described = self.describe_units([str(row["name"]) for row in rows if row["managed"]])

        statuses: list[dict[str, Any]] = []
        for row in rows:
            name = str(row["name"])
            properties = described.get(name) if row["managed"] else None
            if properties is None:
                properties = {"ActiveState": str(row["active"]), "SubState": str(row["sub"])}
            status = self.status_from_properties(name, properties, managed=bool(row["managed"]))
            status["app"] = row.get("app")
            statuses.append(status)
        return statuses

    def get_status(self, name: str, *, require_managed: bool = True) -> dict:
        """
        Get service status.

        Args:
            name: Service name.
            require_managed: Refuse a unit WASM does not own, exactly like
                every other operation here. False is for read-only listings
                across every unit on the host (``all_services=True``), where
                the point is precisely to describe a foreign unit rather than
                refuse it.

        Returns:
            Dictionary with status information. A unit that does not exist is
            reported as absent rather than refused, because callers use this to
            decide whether they still have to create it.

        Raises:
            ServiceError: When ``require_managed`` is true and the unit
                exists but WASM does not manage it.
            ValidationError: When the name is not a safe unit name.
        """
        info = (
            self._require_managed(name, operation="inspect", missing_ok=True)
            if require_managed
            else self.inspect_unit(name)
        )

        # A unit this process cannot see a file for is still queried: the three
        # probes below only read, systemd is the authority on what is running,
        # and a status call that lies about a live service is how a broken
        # deployment gets reported as healthy. ``exists`` reports our own view.
        is_active = self.state_is_running(
            self._exec(["systemctl", "is-active", info.unit_file]).stdout
        )
        is_enabled = (
            self._exec(["systemctl", "is-enabled", info.unit_file]).stdout.strip() == "enabled"
        )

        result = self._exec(["systemctl", "show", info.unit_file, "--no-pager"])
        details: dict[str, str] = {}
        if result.success:
            for line in result.stdout.split("\n"):
                key, separator, value = line.partition("=")
                if separator:
                    details[key] = value

        # "active" alone cannot tell a healthy service from one systemd is
        # restarting every few seconds: a crash loop spends most of its time in
        # activating/auto-restart and reports active in between. active_state,
        # sub_state, restarts and result are what distinguishes the two.
        # "managed" is reported independently of require_managed: a caller that
        # skipped the guard to describe a foreign unit still needs to say so.
        status = self.status_from_properties(
            info.unit, details, managed=info.managed, exists=info.exists
        )
        status["active"] = is_active
        status["enabled"] = is_enabled
        return status

