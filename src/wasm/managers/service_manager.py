    def daemon_reload(self) -> bool:
        """
        Reload systemd daemon.

        Returns:
            True if successful.
        """
        result = self._exec(["systemctl", "daemon-reload"])
        if not result.success:
            self.logger.debug(f"daemon-reload failed: {result.stderr}")
