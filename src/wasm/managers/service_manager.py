#: Marker every generated unit file carries, used to recognise our own units
#: when the store has lost track of them.
WASM_UNIT_MARKER = "Generated by WASM"

#: Starting or restarting an app can take a while: systemd waits for the unit
#: to settle before it answers.
_LIFECYCLE_TIMEOUT = 120

#: ``journalctl -f`` runs until the caller stops reading. The deadline exists
#: because the runner requires one, not because an hour of logs is a limit
#: anybody should hit; callers that need longer pass their own.
_FOLLOW_TIMEOUT = 3600

#: Unit files are not secret - systemd reads them as root and users need to be
#: able to inspect them - but nothing outside root may rewrite one.
UNIT_FILE_MODE = 0o644

#: systemd-analyze verify parses the unit and, for a .service, resolves its
#: ExecStart binary; both are fast, but a deadline is still mandatory.
VERIFY_TIMEOUT = 15


#: The smallest memory limit accepted. Below it a Node or Python process is
#: killed by the OOM killer while it is still loading, which looks like a
#: crash loop rather than a limit.
MIN_MEMORY_MB = 64

#: The smallest task limit accepted. A runtime starts a handful of threads
#: before it runs any application code, and a limit it cannot start under is
#: a unit that never comes up.
MIN_TASKS = 16

#: The directives this manager owns in a unit's ``[Service]`` section.
LIMIT_DIRECTIVES = ("MemoryMax", "CPUQuota", "TasksMax")

#: The leading arguments of every ``systemctl list-units`` this manager runs;
#: the unit patterns follow them.
LIST_UNITS_ARGV = (
    "systemctl",
    "list-units",
    "--type=service",
    "--all",
    "--no-pager",
    "--plain",
)

