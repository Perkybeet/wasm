"""
Tests for per-application memory, CPU and task limits.

- The unit a deploy writes carries ``MemoryMax=``, ``CPUQuota=`` and
  ``TasksMax=`` only for the limits that are set (a snapshot of the whole
  unit pins where and how).
- Setting limits on an existing unit edits it rather than rendering it again,
  and the edit produces exactly what rendering would: one spelling.
- The ranges are enforced in the service manager, whoever asks.
- :func:`wasm.deployers.lifecycle.set_resource_limits` rewrites every unit of
  the application, records the limits on its row and restarts only when asked;
  a redeploy keeps them.
"""

# The service manager fixtures are imported rather than replicated.
# ruff: noqa: F811

from __future__ import annotations

from pathlib import Path
from typing import Any

import pytest
from jinja2 import Environment, PackageLoader

from tests.test_service_manager import (  # noqa: F401  (pytest resolves fixtures by name)
    manager,
    store,
    unit_dirs,
)
from wasm.core.exceptions import DeploymentError, ServiceError, ValidationError
from wasm.core.store import App, Service, WASMStore
from wasm.deployers import lifecycle
from wasm.managers.service_manager import (
    ResourceLimits,
    ServiceManager,
    with_resource_limits,
)

LIMITS = ResourceLimits(memory_max_mb=512, cpu_quota_percent=50, tasks_max=256)

#: The unit a Node application on releases gets with LIMITS, in full.
SNAPSHOT = """\
# Systemd service for shop-example-com
# Generated by WASM

[Unit]
Description=WASM: shop.example.com (nodejs)
Documentation=https://github.com/Perkybeet/wasm
After=network.target
# A transient failure is retried; a hopeless one (a missing script, a missing
# binary) ends in `failed` after five starts in five minutes instead of looping
# every RestartSec forever. Deliberate starts clear the counter first.
StartLimitIntervalSec=300
StartLimitBurst=5

[Service]
Type=simple
User=www-data
Group=www-data
WorkingDirectory=/var/www/apps/shop-example-com/current

# Environment
Environment="PORT=3100"
Environment="NODE_ENV=production"

# Command
ExecStart=/usr/bin/npm run start

# Restart policy
Restart=always
RestartSec=10

# Security
NoNewPrivileges=true
PrivateTmp=true

# Logging
StandardOutput=journal
StandardError=journal
SyslogIdentifier=shop-example-com

# Resource limits
LimitNOFILE=65535
MemoryMax=512M
CPUQuota=50%
TasksMax=256

[Install]
WantedBy=multi-user.target"""


def render(limits: ResourceLimits | None) -> str:
    """Render the application unit template the way the service manager does."""
    return (
        Environment(  # noqa: S701 - unit files, escaped by their own macros
            loader=PackageLoader("wasm", "templates/systemd"), trim_blocks=True, lstrip_blocks=True
        )
        .get_template("app.service.j2")
        .render(
            name="shop-example-com",
            description="WASM: shop.example.com (nodejs)",
            command="/usr/bin/npm run start",
            working_directory="/var/www/apps/shop-example-com/current",
            user="www-data",
            group="www-data",
            environment={"PORT": "3100", "NODE_ENV": "production"},
            resource_limits=(limits or ResourceLimits()).directives(),
        )
    )


# ---------------------------------------------------------------------------
# Rendering
# ---------------------------------------------------------------------------


def test_the_unit_with_limits_is_exactly_the_snapshot() -> None:
    """Where and how the three directives appear, pinned whole."""
    assert render(LIMITS) == SNAPSHOT


def test_a_limit_that_is_not_set_writes_no_directive() -> None:
    """No limit means no line, not an empty or zero value systemd would reject."""
    unit = render(ResourceLimits(tasks_max=64))

    assert "TasksMax=64\n" in unit
    assert "MemoryMax" not in unit and "CPUQuota" not in unit
    assert not any(d in render(None) for d in ("MemoryMax", "CPUQuota", "TasksMax"))


def test_editing_a_unit_gives_what_rendering_it_would() -> None:
    """One spelling: the edit and the template cannot disagree, in either direction."""
    assert with_resource_limits(render(None), LIMITS) == render(LIMITS)
    assert with_resource_limits(render(LIMITS), ResourceLimits()) == render(None)
    changed = ResourceLimits(memory_max_mb=1024)
    assert with_resource_limits(render(LIMITS), changed) == render(changed)


def test_an_edited_unit_keeps_the_operator_own_lines() -> None:
    """A hand edit is no reason to lose it; only the limit directives are replaced."""
    unit = "# Generated by WASM\n[Service]\nExecStart=/bin/app\nNice=5\nMemoryMax=1G\n\n[Install]\n"

    edited = with_resource_limits(unit, ResourceLimits(memory_max_mb=256))

    assert edited == (
        "# Generated by WASM\n[Service]\nExecStart=/bin/app\nNice=5\nMemoryMax=256M\n\n[Install]\n"
    )


def test_a_unit_without_a_service_section_is_refused() -> None:
    """There is nowhere a limit would take effect."""
    with pytest.raises(ServiceError, match=r"\[Service\]"):
        with_resource_limits("[Unit]\nDescription=x\n", LIMITS)


