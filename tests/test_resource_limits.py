@pytest.mark.parametrize(
    "limits",
    [
        ResourceLimits(memory_max_mb=64),
        ResourceLimits(cpu_quota_percent=1),
        ResourceLimits(cpu_quota_percent=400),
        ResourceLimits(tasks_max=16),
        ResourceLimits(),
    ],
)
def test_limits_a_unit_can_run_under_are_accepted(limits: ResourceLimits) -> None:
    """The boundaries themselves are allowed; four CPUs allow 400%."""
    assert limits.validated(cpus=4) == limits


@pytest.mark.parametrize(
    ("limits", "match"),
    [
        (ResourceLimits(memory_max_mb=63), "at least 64M"),
        (ResourceLimits(cpu_quota_percent=0), "1% to 400%"),
        (ResourceLimits(cpu_quota_percent=401), "1% to 400%"),
        (ResourceLimits(tasks_max=15), "at least 16"),
    ],
)
def test_limits_out_of_range_say_what_is_allowed(limits: ResourceLimits, match: str) -> None:
    """The refusal names the range, so the fix is in the message."""
    with pytest.raises(ValidationError) as failure:
        limits.validated(cpus=4)

    assert match in failure.value.details


def test_the_service_manager_is_the_chokepoint(
    manager: ServiceManager, unit_dirs: dict[str, Path]
) -> None:
    """Created or rewritten, a unit gets limits only through the same validation."""
    with pytest.raises(ValidationError):
        manager.create_service(
            name="shop",
            command="/usr/bin/true",
            working_directory="/srv",
            limits=ResourceLimits(memory_max_mb=8),
        )
    with pytest.raises(ValidationError):
        manager.set_resource_limits("shop", ResourceLimits(tasks_max=1))
    assert list(unit_dirs["managed"].iterdir()) == []


def test_limits_are_written_into_a_unit_and_reloaded(
    manager: ServiceManager, unit_dirs: dict[str, Path], runner: Any
) -> None:
    """Created with limits, then changed: the file holds the new ones, systemd reloaded."""
    manager.create_service(
        name="shop", command="/usr/bin/true", working_directory="/srv", limits=LIMITS
    )
    unit = unit_dirs["managed"] / "shop.service"
    assert "MemoryMax=512M\nCPUQuota=50%\nTasksMax=256\n" in unit.read_text()

    previous = manager.set_resource_limits("shop", ResourceLimits(memory_max_mb=128))

    assert "MemoryMax=512M" in previous
    body = unit.read_text()
    assert "MemoryMax=128M\n" in body and "CPUQuota" not in body and "TasksMax" not in body
    assert runner.calls.count(("systemctl", "daemon-reload")) == 2


