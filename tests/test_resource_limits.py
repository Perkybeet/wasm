class FakeUnits:
    """Stands in for ServiceManager: records rewrites and restarts."""

    def __init__(self, fail_on: str | None = None) -> None:
        self.bodies: dict[str, str] = {}
        self.restarts: list[str] = []
        self.fail_on = fail_on

    def set_resource_limits(self, name: str, limits: ResourceLimits) -> str:
        limits.validated()
        if name == self.fail_on:
            raise ServiceError(f"Could not write {name}")
        previous = self.bodies.get(name, "old")
        self.bodies[name] = "\n".join(limits.directives())
        return previous

    def update_config(self, name: str, content: str) -> str:
        previous = self.bodies[name]
        self.bodies[name] = content
        return previous

    def restart(self, name: str) -> None:
        self.restarts.append(name)

    def logs(self, name: str, lines: int = 50) -> str:
        return "Out of memory: Killed process 4242 (node)"


@pytest.fixture
def sqlite_store(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> Any:
    """A store where the lifecycle looks for it."""
    WASMStore.reset_instance()
    instance = WASMStore(tmp_path / "wasm.db")
    monkeypatch.setattr(lifecycle, "get_store", lambda: instance)
    yield instance
    WASMStore.reset_instance()


def deploy(store: WASMStore, *, app_type: str = "nodejs", units: tuple[str, ...] = ()) -> App:
    """Register an application and the units it runs as."""
    app = store.create_app(
        App(domain="shop.example.com", app_type=app_type, port=3100, app_path="/srv/shop")
    )
    for name in units:
        store.create_service(Service(app_id=app.id, name=name, command="x", working_directory="/"))
    return app


def test_every_unit_of_the_application_gets_the_limits_and_the_row_keeps_them(
    sqlite_store: WASMStore, monkeypatch: pytest.MonkeyPatch
) -> None:
    """A monorepo's workspaces are limited alike; no restart unless asked."""
    deploy(sqlite_store, app_type="monorepo", units=("shop-web", "shop-api"))
    units = FakeUnits()
    monkeypatch.setattr(lifecycle, "ServiceManager", lambda **kw: units)

    change = lifecycle.set_resource_limits("shop.example.com", LIMITS)

    assert sorted(change.units) == ["shop-api", "shop-web"]
    assert units.bodies == dict.fromkeys(change.units, "MemoryMax=512M\nCPUQuota=50%\nTasksMax=256")
    assert units.restarts == [] and not change.restarted
    app = sqlite_store.get_app("shop.example.com")
    assert app is not None
    assert (app.memory_max_mb, app.cpu_quota_percent, app.tasks_max) == (512, 50, 256)

    probes: list[str] = []
    monkeypatch.setattr(
        lifecycle, "wait_until_healthy", lambda url, **kw: probes.append(url) or True
    )
    lifecycle.set_resource_limits("shop.example.com", LIMITS, restart=True)
    assert sorted(units.restarts) == ["shop-api", "shop-web"]
    assert probes == ["http://127.0.0.1:3100/"], "restarted means proven to answer"


def test_limits_it_cannot_run_under_are_put_back(
    sqlite_store: WASMStore, monkeypatch: pytest.MonkeyPatch
) -> None:
    """Restarted under a limit it dies of, the application gets its old units back."""
    deploy(sqlite_store, units=("shop",))
    units = FakeUnits()
    units.bodies["shop"] = "MemoryMax=2048M"
    monkeypatch.setattr(lifecycle, "ServiceManager", lambda **kw: units)
    answers = iter([False, True])
    monkeypatch.setattr(lifecycle, "wait_until_healthy", lambda url, **kw: next(answers))

    with pytest.raises(DeploymentError, match="previous ones are running again") as failure:
        lifecycle.set_resource_limits(
            "shop.example.com", ResourceLimits(memory_max_mb=64), restart=True
        )

    assert "Out of memory" in failure.value.details
    assert units.bodies == {"shop": "MemoryMax=2048M"}
    assert units.restarts == ["shop", "shop"]
    app = sqlite_store.get_app("shop.example.com")
    assert app is not None and app.memory_max_mb is None


def test_a_unit_that_cannot_be_written_puts_the_others_back(
    sqlite_store: WASMStore, monkeypatch: pytest.MonkeyPatch
) -> None:
    """All or none; the row is not changed either."""
    deploy(sqlite_store, units=("shop-api", "shop-web"))
    order = [s.name for s in sqlite_store.list_services()]
    units = FakeUnits(fail_on=order[-1])
    monkeypatch.setattr(lifecycle, "ServiceManager", lambda **kw: units)

    with pytest.raises(ServiceError):
        lifecycle.set_resource_limits("shop.example.com", LIMITS)

    assert units.bodies == {order[0]: "old"}
    app = sqlite_store.get_app("shop.example.com")
    assert app is not None and app.memory_max_mb is None


@pytest.mark.parametrize(
    ("app_type", "is_static", "match"),
    [("docker-compose", False, "compose file"), ("static", True, "static site")],
)
def test_applications_with_no_unit_of_their_own_are_refused(
    sqlite_store: WASMStore,
    monkeypatch: pytest.MonkeyPatch,
    app_type: str,
    is_static: bool,
    match: str,
) -> None:
    """The limit would not reach what runs, so it is refused with where it belongs."""
    app = deploy(sqlite_store, app_type=app_type)
    app.is_static = is_static
    sqlite_store.update_app(app)
    monkeypatch.setattr(lifecycle, "ServiceManager", lambda **kw: FakeUnits())

    with pytest.raises(DeploymentError) as failure:
        lifecycle.set_resource_limits("shop.example.com", LIMITS)

    assert match in f"{failure.value.message} {failure.value.details}"


def test_a_redeploy_writes_the_recorded_limits_into_the_new_unit(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    """The limits are the application's, not the deployment's."""
    from tests.test_release_pipeline import FakeServices
    from wasm.deployers.nodejs import NodeJSDeployer

    WASMStore.reset_instance()
    instance = WASMStore(tmp_path / "wasm.db")
    try:
        existing = instance.create_app(
            App(domain="shop.example.com", app_type="nodejs", app_path=str(tmp_path))
        )
        existing.memory_max_mb, existing.tasks_max = 768, 128
        instance.update_app(existing)
        deployer = NodeJSDeployer()
        deployer.store = instance
        services = FakeServices(tmp_path)
        deployer.service_manager = services
        deployer._resolve_absolute_path = lambda command: command
        deployer.configure("shop.example.com", str(tmp_path), port=3100, app_path=tmp_path)
        deployer._app_record = deployer._register_app_in_store("deploying")

        deployer.create_service()
    finally:
        WASMStore.reset_instance()

    assert services.units["shop-example-com"]["limits"] == ResourceLimits(
        memory_max_mb=768, tasks_max=128
    )
