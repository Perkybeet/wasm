def snapshot(root: Path) -> dict[str, tuple[Any, ...]]:
    """
    Describe a tree exactly: every entry, its type, mode, link target and content hash.

    Returns:
        Relative path to description.
    """
    described: dict[str, tuple[Any, ...]] = {}
    for directory, subdirectories, names in os.walk(root):
        for name in [*subdirectories, *names]:
            path = Path(directory) / name
            info = os.lstat(path)
            relative = str(path.relative_to(root))
            if stat.S_ISLNK(info.st_mode):
                described[relative] = ("link", os.readlink(path))
            elif stat.S_ISDIR(info.st_mode):
                described[relative] = ("dir", stat.S_IMODE(info.st_mode))
            else:
                digest = hashlib.sha256(path.read_bytes()).hexdigest()
                described[relative] = ("file", stat.S_IMODE(info.st_mode), digest)
    return described


def files_by_content(root: Path) -> dict[str, str]:
    """Relative path to content hash, regular files only."""
    return {path: entry[2] for path, entry in snapshot(root).items() if entry[0] == "file"}


