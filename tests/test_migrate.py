def test_a_file_lost_on_the_way_fails_the_migration(
    root: Path, store: WASMStore, machine: Any
) -> None:
    """The count is the proof: one file fewer, anywhere, and the migration is undone."""
    plan = plan_migration(DOMAIN)

    class LosingMoves(RealFileSystem):
        def move(self, source: Path, destination: Path) -> None:
            super().move(source, destination)
            if destination.name == "uploads" and destination.parent.name == "shared":
                (destination / "photo.jpg").unlink()

    set_fs(LosingMoves())
    with pytest.raises(DeploymentError, match="before the migration") as failure:
        migrate(DOMAIN, plan)
    set_fs(None)

    assert "Not put back" in failure.value.details, "the loss is reported, not hidden"
    assert not os.path.lexists(root / "current")
    assert (root / "uploads" / "2026" / "doc.pdf").read_text() == "user document"
    assert machine.units.restarts == ["in place"]
    app = store.get_app(DOMAIN)
    assert app is not None and app.layout == "inplace"


