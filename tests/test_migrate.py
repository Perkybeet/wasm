def test_the_live_tree_becomes_the_first_release_and_uploads_move_to_shared(
    root: Path, store: WASMStore, machine: Any
) -> None:
    """Review Focus: every upload in shared/, served through the release; not a byte lost."""
    before_files = files_by_content(root)
    plan = plan_migration(DOMAIN)

    result = migrate(DOMAIN, plan, trigger="panel")

    release = root / "releases" / result.release_id
    assert os.readlink(root / "current") == f"releases/{result.release_id}"
    assert result.release_id.endswith(f"-{COMMIT[:7]}")
    assert sorted(os.listdir(root)) == ["current", "releases", "shared"]

    # Every file of the in-place tree is somewhere, byte for byte.
    after_files = files_by_content(root)
    for old, digest in before_files.items():
        top = old.split("/")[0]
        if top in plan.persistent or top in plan.env_files:
            new = f"shared/{old}"
        else:
            new = f"releases/{result.release_id}/{old}"
        assert after_files.get(new) == digest, f"{old} is not at {new}"
    assert len(after_files) == len(before_files)
    assert (result.before.files, result.before.bytes) == (result.after.files, result.after.bytes)

    # Served through the release, through relative links.
    assert os.readlink(release / "uploads") == "../../shared/uploads"
    assert os.readlink(release / ".env") == "../../shared/.env"
    assert os.readlink(release / ".env.local") == "../../shared/.env.local"
    assert (root / "current" / "uploads" / "2026" / "doc.pdf").read_text() == "user document"
    assert stat.S_IMODE((root / "shared" / ".env").stat().st_mode) == 0o600
    # A link the application had is still the same link.
    assert os.readlink(release / "node_modules" / ".bin" / "dep") == "../dep/index.js"

    # The unit runs from current; the proxied site did not need rewriting.
    assert f"WorkingDirectory={root}/current\n" in machine.units.bodies["shop-example-com"]
    assert machine.units.restarts == [f"releases/{result.release_id}"]
    assert (result.unit_rewritten, result.site_rewritten) == (True, False)
    service = store.get_service("shop-example-com")
    assert service is not None and service.working_directory == str(root / "current")

    app = store.get_app(DOMAIN)
    assert app is not None and app.layout == "releases"
    assert app.persistent_paths == [".env.local", "uploads"]
    assert [(r.id, r.status) for r in store.list_releases(app.id)] == [
        (result.release_id, "active")
    ]
    history = store.list_deployments(DOMAIN)[0]
    assert (history.status, history.triggered_by) == ("success", "panel")

    # New directories are the service's; the application directory is root's again.
    calls = machine.runner.calls
    assert ("chown", "www-data:www-data", str(release)) in calls
    assert ("chown", "www-data:www-data", str(root / "shared")) in calls
    assert ("chown", "root:root", str(root)) in calls


