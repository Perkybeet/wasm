def test_the_top_bar_tally_equals_the_services_list(
    runner: FakeRunner, unit_dirs: dict[str, Path], store: WASMStore, api: TestClient
) -> None:
    """Two implementations disagreed; now both read managed_units."""
    deploy(store, "one.example.com")
    marked(unit_dirs, "one-example-com")
    deploy(store, "old.example.com")
    marked(unit_dirs, "wasm-old-example-com")
    marked(unit_dirs, "wasm-monitor")
    marked(unit_dirs, "idle-example-com")
    store.create_service(Service(name="hand-made", command="/usr/bin/true"))
    marked(unit_dirs, "hand-made")
    runner.script(
        LIST_UNITS,
        stdout=listing(
            "one-example-com loaded active running",
            "wasm-old-example-com loaded failed failed",
            "wasm-monitor loaded active running",
            "hand-made loaded inactive dead",
        ),
    )

    tally = read_machine(apps_root="/tmp").units
    response = api.get("/api/services")

    assert response.status_code == 200, response.text
    body = response.json()
    assert body["total"] == tally.running + tally.failed + tally.stopped == 5
    assert {row["name"] for row in body["services"]} == {
        "one-example-com",
        "wasm-old-example-com",
        "wasm-monitor",
        "idle-example-com",
        "hand-made",
    }
    hand_made = next(row for row in body["services"] if row["name"] == "hand-made")
    assert hand_made["description"] == "/usr/bin/true"


def test_the_services_page_describes_every_managed_unit_in_one_call(
    runner: FakeRunner, unit_dirs: dict[str, Path], store: WASMStore, api: TestClient
) -> None:
    """PID, memory and boot setting come from one systemctl show, not three calls per unit."""
    marked(unit_dirs, "one-example-com")
    marked(unit_dirs, "two-example-com")
    runner.script(
        LIST_UNITS,
        stdout=listing(
            "one-example-com loaded active running", "two-example-com loaded inactive dead"
        ),
    )
    runner.script(
        ["systemctl", "show", "--no-pager"],
        stdout=(
            "Id=one-example-com.service\nActiveState=active\nSubState=running\n"
            "MainPID=4242\nMemoryCurrent=1048576\nUnitFileState=enabled\nNRestarts=0\n\n"
            "Id=two-example-com.service\nActiveState=inactive\nSubState=dead\n"
            "MainPID=0\nUnitFileState=disabled\nNRestarts=0\n"
        ),
    )

    body = api.get("/api/services").json()

    rows = {row["name"]: row for row in body["services"]}
    assert rows["one-example-com"]["pid"] == 4242
    assert rows["one-example-com"]["enabled"] is True
    assert rows["one-example-com"]["status"] == "running"
    assert rows["two-example-com"]["enabled"] is False
    assert rows["two-example-com"]["pid"] is None
    shows = [call for call in runner.calls if call[:2] == ("systemctl", "show")]
    assert len(shows) == 1
    assert not any(call[:2] == ("systemctl", "is-active") for call in runner.calls)


