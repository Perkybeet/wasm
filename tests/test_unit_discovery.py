def marked(unit_dirs: dict[str, Path], name: str) -> Path:
    """
    Write a unit file as WASM's templates do.

    Args:
        unit_dirs: The unit directories.
        name: Unit name without ``.service``.

    Returns:
        The file.
    """
    path = unit_dirs["managed"] / f"{name}.service"
    path.write_text(f"# Systemd service for {name}\n# {WASM_UNIT_MARKER}\n[Service]\n")
    return path


def deploy(store: WASMStore, domain: str, **fields: Any) -> App:
    """
    Record an application.

    Args:
        store: The store.
        domain: Its domain.
        **fields: Overrides.

    Returns:
        The stored application.
    """
    values: dict[str, Any] = {
        "domain": domain,
        "app_type": "nextjs",
        "port": 3000,
        "app_path": f"/var/www/apps/{domain_to_app_name(domain)}",
        "is_static": False,
    }
    values.update(fields)
    return store.create_app(App(**values))


def listing(*rows: str) -> str:
    """
    Build ``systemctl list-units --plain`` output.

    Args:
        *rows: ``"name load active sub"`` lines, without the suffix.

    Returns:
        The output, header included.
    """
    lines = ["UNIT LOAD ACTIVE SUB DESCRIPTION"]
    for row in rows:
        name, rest = row.split(" ", 1)
        lines.append(f"{name}.service {rest} Description")
    return "\n".join(lines) + "\n"


