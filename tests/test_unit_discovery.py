def test_all_units_lists_systemd_escaped_names_without_probing_them(
    runner: FakeRunner, unit_dirs: dict[str, Path], store: WASMStore, api: TestClient
) -> None:
    """Listing every unit used to fail as a whole on 'systemd-fsck@dev-disk-by\\x2dlabel-BOOT'."""
    marked(unit_dirs, "one-example-com")
    runner.script(
        [*LIST_UNITS, "*"],
        stdout=listing(
            f"{ESCAPED} loaded inactive dead",
            "getty@tty1 loaded active running",
            "ssh loaded active running",
            "one-example-com loaded active running",
        ),
    )

    response = api.get("/api/services", params={"wasm_only": "false"})

    assert response.status_code == 200, response.text
    rows = {row["name"]: row for row in response.json()["services"]}
    assert set(rows) == {ESCAPED, "getty@tty1", "ssh", "one-example-com"}
    assert rows[ESCAPED]["managed"] is False
    assert rows[ESCAPED]["status"] == "stopped"
    assert rows["ssh"]["active"] is True
    assert rows["ssh"]["managed"] is False
    assert rows["one-example-com"]["managed"] is True
    # One listing; foreign units are never asked about one by one.
    systemctl = runner.calls_to("systemctl")
    assert sum(call[1] == "list-units" for call in systemctl) == 1
    assert not any(ESCAPED + ".service" in call for call in systemctl if call[1] != "list-units")
    assert not any(call[1] in {"is-active", "is-enabled"} for call in systemctl)


