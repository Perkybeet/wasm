class _Journal:
    """A journalctl that says what the test scripted, then ends."""

    def __init__(self, lines: list[bytes], error: bytes = b"", code: int = 0) -> None:
        self.returncode: int | None = None
        self._code = code
        self.stdout = asyncio.StreamReader()
        for line in lines:
            self.stdout.feed_data(line)
        if not lines:
            self.stdout.feed_eof()
        self.stderr = asyncio.StreamReader()
        if error:
            self.stderr.feed_data(error)
        self.stderr.feed_eof()

    def terminate(self) -> None:
        self.returncode = self._code

    def kill(self) -> None:
        self.returncode = -9

    async def wait(self) -> int:
        self.returncode = self._code
        return self._code


@pytest.fixture
def journal(monkeypatch: pytest.MonkeyPatch) -> dict[str, Any]:
    """
    Stand in for journalctl.

    Returns:
        ``calls`` (every argv spawned) and ``make`` (what the next spawn returns).
    """
    state: dict[str, Any] = {
        "calls": [],
        "make": lambda: _Journal([b"2026-09-26T10:00:00 host app[1]: hello\n"]),
    }

    async def fake_exec(*argv: str, **_kwargs: Any) -> _Journal:
        state["calls"].append(tuple(argv))
        return state["make"]()

    monkeypatch.setattr(asyncio, "create_subprocess_exec", fake_exec)
    monkeypatch.setattr("shutil.which", lambda name: f"/usr/bin/{name}")
    return state


def _open(sandbox: Path, path: str, frames: int) -> list[dict[str, Any]]:
    """
    Open a log socket and read some frames.

    Args:
        sandbox: The per-test sandbox.
        path: The socket path.
        frames: How many frames to read.

    Returns:
        The frames.
    """
    client = build_client(sandbox)
    token = get_token_manager().generate_master_token()
    with client.websocket_connect(path, subprotocols=token_subprotocols(token)) as ws:
        return [ws.receive_json() for _ in range(frames)]


