"""
One definition of "the units WASM manages", read by every view.

On the owner's production fifteen application units and ``wasm-monitor`` all
carried the ``Generated by WASM`` marker, and the console's top bar still said
"Units 1": :meth:`ServiceManager.list_services` asked systemd for ``wasm-*``
plus the names in the services table, while application units have had no
prefix since 0.14.1 and the table had no row for them. The Services page read
another source, so the two disagreed; "show all units" failed as a whole on the
first name systemd had escaped; and the live log stream derived a unit from the
domain alone, so legacy, monorepo and Compose units were refused.

What is pinned here, all through the real manager on a fake runner:

- an application unit counts whether or not it has a prefix or a store row;
- the top bar's tally is exactly the Services page's list;
- a monorepo's workspace units and a legacy ``wasm-`` unit belong to their
  application;
- every unit on the machine is listed from one ``list-units``, escaped names
  included, without a probe per unit;
- the log stream finds an application's unit(s) the same way, says why a static
  site has nothing to stream, and forwards journalctl's own error;
- a deliberate start clears systemd's start limit first.
"""

