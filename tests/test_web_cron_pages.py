"""
Tests for the cron jobs page and its API.

The page is a thin client of the cron API; the API is a thin client of the
manager; these tests hold both to that. What is asserted is the exact argv
systemctl receives and the exact unit files written into a sandboxed systemd
directory - never a real process.

The refusals matter most: a calendar the manager would not write answers with
the manager's own words and nothing half-written, and deleting demands the
job's exact name typed back, compared server-side, because a ``required``
attribute on an input is a courtesy, not a guard.
"""

# The web fixtures are imported from test_web_views rather than replicated, so
# there stays one definition of "a signed-in panel client". Ruff reads a test
# parameter named after an imported fixture as a redefinition; here it is the
# mechanism.
# ruff: noqa: F811

