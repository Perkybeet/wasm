def test_run_now_starts_the_service(
    client: TestClient, runner: FakeRunner, systemd_dir: Path
) -> None:
    """The Run now button drives one systemctl start of the service unit."""
    write_owned_pair(systemd_dir)
    scripted_job(runner)

    response = client.post("/cron/jobs/cleanup/run")

    assert response.status_code == 200, response.text
    assert ("systemctl", "start", "--no-block", "wasm-cron-cleanup.service") in runner.calls
    assert "Started wasm-cron-cleanup.service" in response.text


def test_enable_and_disable_drive_the_timer(
    client: TestClient, runner: FakeRunner, systemd_dir: Path
) -> None:
    """The toggle posts to the right verb and reports what it did."""
    write_owned_pair(systemd_dir)
    scripted_job(runner)

    disabled = client.post("/cron/jobs/cleanup/disable")
    enabled = client.post("/cron/jobs/cleanup/enable")

    assert ("systemctl", "disable", "--now", "wasm-cron-cleanup.timer") in runner.calls
    assert ("systemctl", "enable", "--now", "wasm-cron-cleanup.timer") in runner.calls
    assert "Disabled wasm-cron-cleanup.timer" in disabled.text
    assert "Enabled wasm-cron-cleanup.timer" in enabled.text


def test_deleting_demands_the_exact_name_typed_back(
    client: TestClient, runner: FakeRunner, systemd_dir: Path
) -> None:
    """A mismatch deletes nothing and says so; the match tears the pair down."""
    timer, service = write_owned_pair(systemd_dir)
    scripted_job(runner)

    refused = client.post("/cron/jobs/cleanup/delete", data={"confirm": "clean"})

    assert refused.status_code == 200
    assert "Nothing was deleted" in refused.text
    assert timer.exists() and service.exists()
    assert ("systemctl", "stop", "wasm-cron-cleanup.timer") not in runner.calls

    accepted = client.post("/cron/jobs/cleanup/delete", data={"confirm": "cleanup"})

    assert accepted.status_code == 200
    assert "Cron job cleanup deleted" in accepted.text
    assert not timer.exists() and not service.exists()
    assert ("systemctl", "stop", "wasm-cron-cleanup.timer") in runner.calls


def test_deleting_a_job_that_does_not_exist_answers_the_refusal_inline(
    client: TestClient, runner: FakeRunner, systemd_dir: Path
) -> None:
    """A delete that removed nothing must not report success."""
    response = client.post("/cron/jobs/ghost/delete", data={"confirm": "ghost"})

    assert response.status_code == 200
    assert "No cron job named ghost" in response.text


def test_a_foreign_unit_is_refused_from_the_panel_too(
    client: TestClient, runner: FakeRunner, systemd_dir: Path
) -> None:
    """The ownership guard's words reach the operator, not a blank screen."""
    (systemd_dir / "wasm-cron-cleanup.timer").write_text("[Timer]\nOnCalendar=hourly\n")

    response = client.post("/cron/jobs/cleanup/run")

    assert response.status_code == 200
    assert "does not manage" in response.text
    assert not any(call[:2] == ("systemctl", "start") for call in runner.calls)


# ----------------------------------------------------------------- history


def test_the_history_renders_the_runs_output_verbatim_and_escaped(
    client: TestClient, runner: FakeRunner, systemd_dir: Path
) -> None:
    """The journal's text reaches the page whole, with its markup inert."""
    write_owned_pair(systemd_dir)
    runner.script(("journalctl",), stdout=JOURNAL_OUTPUT)

    body = body_of(client, "/cron/jobs/cleanup/runs")

    assert MISSING_MARKER not in body
    assert "ERROR: disk full" in body
    # Escaped, not stripped: the operator reads exactly what the job printed.
    assert "&lt;b&gt;boom-11&lt;/b&gt;" in body
    assert "<b>boom-11</b>" not in body
    assert "exit 2" in body
    assert "2023-11-14 22:13:20 UTC" in body


def test_a_job_with_no_recorded_runs_says_so(
    client: TestClient, runner: FakeRunner, systemd_dir: Path
) -> None:
    """An empty history is an explanation, not a blank fragment."""
    write_owned_pair(systemd_dir)
    runner.script(("journalctl",), stdout="")

    body = body_of(client, "/cron/jobs/cleanup/runs")

    assert MISSING_MARKER not in body
    assert "No recorded runs" in body


