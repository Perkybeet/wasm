def test_the_page_demands_a_session(anonymous: TestClient) -> None:
    """The cron screen redirects to the sign-in form, like every page."""
    response = anonymous.get("/cron")
    assert response.status_code == 303
    assert response.headers["location"] == "/login"

    section = anonymous.get("/cron/jobs")
    assert section.status_code == 303


def test_the_api_demands_a_session(anonymous: TestClient) -> None:
    """The cron endpoints are not a hole in the fence."""
    assert anonymous.get("/api/cron").status_code in (401, 403)
    assert anonymous.post("/api/cron", json={"name": "x", "command": "/bin/true"}).status_code in (
        401,
        403,
    )
    assert anonymous.delete("/api/cron/x").status_code in (401, 403)
    assert anonymous.post("/api/cron/x/run").status_code in (401, 403)
    assert anonymous.get("/api/cron/x/runs").status_code in (401, 403)


def test_the_page_loads_the_section(client: TestClient) -> None:
    """The page hands the browser the section's address."""
    body = body_of(client, "/cron")

    assert MISSING_MARKER not in body
    assert 'hx-get="/cron/jobs"' in body
    assert "Cron jobs" in body


def test_the_empty_section_renders_and_documents_the_no_shell_rule(
    client: TestClient, runner: FakeRunner, systemd_dir: Path
) -> None:
    """An empty machine still shows the form, and the form tells the truth."""
    body = body_of(client, "/cron/jobs")

    assert MISSING_MARKER not in body
    assert "No cron jobs" in body
    # The shlex decision is documented where the command is typed.
    assert "without a shell" in body
    assert "/bin/sh -c" in body


def test_the_section_renders_each_job(
    client: TestClient, runner: FakeRunner, systemd_dir: Path
) -> None:
    """The row names the job, the command in mono, the schedule and the exit."""
    write_owned_pair(systemd_dir)
    scripted_job(runner)

    body = body_of(client, "/cron/jobs")

    assert MISSING_MARKER not in body
    assert "cleanup" in body
    assert "/usr/bin/find /tmp/caches -delete" in body
    assert "*-*-* 02:00:00" in body
    assert "Sat 2026-08-15 02:00:00 UTC" in body
    # The last run failed with 2: the rail and the badge both say failed.
    assert "row--failed" in body
    assert "exit 2" in body
    assert "example.com" in body


def test_creating_from_the_form_writes_the_units_and_enables_the_timer(
    client: TestClient, runner: FakeRunner, systemd_dir: Path
) -> None:
    """The htmx form drives the same create the JSON API drives."""
    response = client.post(
        "/cron/jobs",
        data={
            "name": "cleanup",
            "command": "/usr/bin/find /tmp/caches -delete",
            "schedule": "daily",
            "user": "www-data",
            "working_directory": "/srv/caches",
        },
    )

    assert response.status_code == 200, response.text
    assert "Cron job cleanup created" in response.text
    timer = systemd_dir / "wasm-cron-cleanup.timer"
    service = systemd_dir / "wasm-cron-cleanup.service"
    assert "OnCalendar=*-*-* 02:00:00" in timer.read_text()
    assert "ExecStart=/usr/bin/find /tmp/caches -delete" in service.read_text()
    assert ("systemctl", "enable", "--now", "wasm-cron-cleanup.timer") in runner.calls


def test_a_refused_calendar_renders_inline_and_writes_nothing(
    client: TestClient, runner: FakeRunner, systemd_dir: Path
) -> None:
    """
    htmx does not swap an error status, so the refusal answers 200 with the
    manager's words on the fragment - and no unit half-written behind it.
    """
    response = client.post(
        "/cron/jobs",
        data={
            "name": "cleanup",
            "command": "/usr/bin/true",
            "schedule": "custom",
            "on_calendar": INJECTED_CALENDAR,
        },
    )

    assert response.status_code == 200
    assert "Invalid cron schedule" in response.text
    assert list(systemd_dir.iterdir()) == []
    # The operator's input survives the refusal.
    assert "/usr/bin/true" in response.text


