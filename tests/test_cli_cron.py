def test_run_starts_the_service_unit(
    cli_runner: CliRunner, runner: FakeRunner, systemd_dir: Path
) -> None:
    """``wasm cron run`` starts the service outside its schedule."""
    write_owned_pair(systemd_dir)

    result = cli_runner.invoke(cron_cli.cli, ["run", "cleanup"])

    assert result.exit_code == 0, result.output
    assert "Started wasm-cron-cleanup.service" in result.output
    assert ("systemctl", "start", "--no-block", "wasm-cron-cleanup.service") in runner.calls


def test_enable_and_disable_drive_the_timer(
    cli_runner: CliRunner, runner: FakeRunner, systemd_dir: Path
) -> None:
    """Enable and disable act on the timer unit and report which one."""
    write_owned_pair(systemd_dir)

    enabled = cli_runner.invoke(cron_cli.cli, ["enable", "cleanup"])
    disabled = cli_runner.invoke(cron_cli.cli, ["disable", "cleanup"])

    assert enabled.exit_code == 0, enabled.output
    assert "Enabled wasm-cron-cleanup.timer" in enabled.output
    assert ("systemctl", "enable", "--now", "wasm-cron-cleanup.timer") in runner.calls

    assert disabled.exit_code == 0, disabled.output
    assert "Disabled wasm-cron-cleanup.timer" in disabled.output
    assert ("systemctl", "disable", "--now", "wasm-cron-cleanup.timer") in runner.calls


def test_run_of_an_unowned_unit_is_refused(
    cli_runner: CliRunner, runner: FakeRunner, systemd_dir: Path
) -> None:
    """A unit without the WASM marker is never started, enabled or disabled."""
    (systemd_dir / "wasm-cron-cleanup.timer").write_text("[Timer]\nOnCalendar=daily\n")
    (systemd_dir / "wasm-cron-cleanup.service").write_text("[Service]\nExecStart=/bin/true\n")

    result = cli_runner.invoke(cron_cli.cli, ["run", "cleanup"])

    assert result.exit_code == 1
    assert "Refusing" in result.output
    assert not any(call[:2] == ("systemctl", "start") for call in runner.calls_to("systemctl"))


