def test_create_writes_the_unit_pair_and_enables_it(
    cli_runner: CliRunner, runner: FakeRunner, systemd_dir: Path, config_file: Path
) -> None:
    """A valid job is written through the manager and its timer enabled."""
    result = cli_runner.invoke(
        cron_cli.cli,
        ["create", "cleanup", "/usr/bin/find /tmp/caches -delete", "--schedule", "daily"],
    )

    assert result.exit_code == 0, result.output
    assert "Created cron job: cleanup" in result.output
    assert (systemd_dir / "wasm-cron-cleanup.timer").exists()
    assert (systemd_dir / "wasm-cron-cleanup.service").exists()
    assert ("systemctl", "enable", "--now", "wasm-cron-cleanup.timer") in runner.calls


def test_create_refuses_an_invalid_schedule(
    cli_runner: CliRunner, runner: FakeRunner, systemd_dir: Path, config_file: Path
) -> None:
    """
    The same calendar rule the panel enforces is enforced here.

    wasm.managers.backup_scheduler.validate_calendar is the single definition
    both wasm.web.api.cron and this command go through, so a value the panel
    would answer 422 for is refused here in the same words instead of being
    written into a root-owned unit file. A newline is what an operator could
    use to append a directive to the unit, which is exactly what the
    character allowlist exists to catch.
    """
    result = cli_runner.invoke(
        cron_cli.cli,
        ["create", "cleanup", "/usr/bin/true", "--schedule", "daily\nOnBootSec=1s"],
    )

    assert result.exit_code == 1
    assert "Invalid cron schedule" in result.output
    assert list(systemd_dir.iterdir()) == []


def test_create_refuses_an_unparseable_command(
    cli_runner: CliRunner, runner: FakeRunner, systemd_dir: Path, config_file: Path
) -> None:
    """A dangling quote is refused before anything is written."""
    result = cli_runner.invoke(cron_cli.cli, ["create", "cleanup", "/usr/bin/echo 'unterminated"])

    assert result.exit_code == 1
    assert "Cannot parse" in result.output
    assert list(systemd_dir.iterdir()) == []


