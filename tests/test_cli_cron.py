def test_delete_with_force_removes_the_unit_pair(
    cli_runner: CliRunner, runner: FakeRunner, systemd_dir: Path
) -> None:
    """--force skips the confirmation and removes both unit files."""
    timer, service = write_owned_pair(systemd_dir)

    result = cli_runner.invoke(cron_cli.cli, ["delete", "cleanup", "--force"])

    assert result.exit_code == 0, result.output
    assert "Deleted cron job: cleanup" in result.output
    assert not timer.exists()
    assert not service.exists()


def test_delete_without_force_asks_first(
    cli_runner: CliRunner, runner: FakeRunner, systemd_dir: Path
) -> None:
    """Declining the confirmation leaves the unit pair untouched."""
    timer, service = write_owned_pair(systemd_dir)

    result = cli_runner.invoke(cron_cli.cli, ["delete", "cleanup"], input="n\n")

    assert result.exit_code == 0, result.output
    assert "Cancelled" in result.output
    assert timer.exists()
    assert service.exists()


def test_delete_of_an_unknown_job_fails(cli_runner: CliRunner, runner: FakeRunner) -> None:
    """Deleting a job that was never created is an error, not a silent no-op."""
    result = cli_runner.invoke(cron_cli.cli, ["delete", "nosuch", "--force"])

    assert result.exit_code == 1
    assert "Unknown cron job" in result.output


