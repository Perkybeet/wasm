"""
Tests for the ``wasm cron`` command group.

The commands are a thin shell around
:class:`~wasm.managers.cron_manager.CronManager`, which is exercised for real
here (through the escaped systemd templates, a sandboxed unit directory and
the :class:`~wasm.core.runner.FakeRunner`) rather than mocked out, so a
divergence between the CLI and the manager's own validation - the same
validation :mod:`wasm.web.api.cron` relies on - would show up as a failing
test rather than shipping.
"""

